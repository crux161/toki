#!/usr/bin/env python3
"""Generate src/Glyphs.c from the glyph PNGs in resources/glyphs/.

Each glyph is thresholded to a single bit per pixel (white = foreground) and
packed MSB-first, GLYPH_ROW_BYTES per row, so the clock can render without
reading any image file at run time.

Regenerate with:  python3 scripts/gen_glyphs.py
Requires:         Pillow
"""

from pathlib import Path
import sys

from PIL import Image

GLYPH_DIR = Path("resources/glyphs")
OUTPUT = Path("src/Glyphs.c")

# Index order is part of the ABI in src/Glyphs.h: digits 0-9, then the colon.
GLYPHS = [(str(d), f"digit_{d}.png") for d in range(10)] + [(":", "separator.png")]

THRESHOLD = 128


def load_mask(path):
    """Return (width, height, rows) where rows[y][x] is 1 for a foreground pixel."""
    image = Image.open(path).convert("L")
    width, height = image.size
    pixels = image.load()
    rows = [
        [1 if pixels[x, y] > THRESHOLD else 0 for x in range(width)]
        for y in range(height)
    ]
    return width, height, rows


def pack_row(row):
    """Pack one row of bits MSB-first into ceil(len(row) / 8) bytes."""
    out = bytearray()
    for start in range(0, len(row), 8):
        byte = 0
        for offset, bit in enumerate(row[start:start + 8]):
            byte |= bit << (7 - offset)
        out.append(byte)
    return bytes(out)


def main():
    if not GLYPH_DIR.is_dir():
        sys.exit(f"error: {GLYPH_DIR} not found; run from the repository root")

    masks = []
    for label, filename in GLYPHS:
        path = GLYPH_DIR / filename
        if not path.exists():
            sys.exit(f"error: missing glyph {path}")
        masks.append((label, filename, *load_mask(path)))

    widths = {m[2] for m in masks}
    heights = {m[3] for m in masks}
    if len(widths) != 1 or len(heights) != 1:
        sys.exit(f"error: glyph sizes disagree: widths {widths}, heights {heights}")

    width, height = widths.pop(), heights.pop()
    row_bytes = (width + 7) // 8

    lines = [
        "/*",
        f" * Auto-generated by {Path(__file__).name} from {GLYPH_DIR}/. Do not edit.",
        " *",
        f" * {len(masks)} glyphs at {width}x{height}, one bit per pixel, MSB first,",
        f" * {row_bytes} bytes per row. White in the source PNG is a foreground pixel.",
        " */",
        "",
        '#include "Glyphs.h"',
        "",
        f"const uint8_t g_glyph_bits[GLYPH_COUNT][GLYPH_HEIGHT][GLYPH_ROW_BYTES] = {{",
    ]

    for index, (label, filename, _w, _h, rows) in enumerate(masks):
        packed = [pack_row(row) for row in rows]
        assert all(len(p) == row_bytes for p in packed)

        name = "separator" if label == ":" else f"digit_{label}"
        lines.append(f"\t{{ /* [{index}] {name} <- {filename} */")
        for row in packed:
            # Braces per row: without them clang warns -Wmissing-braces on all
            # 781 rows of the innermost dimension.
            lines.append("\t\t{" + ",".join(f"0x{b:02x}" for b in row) + "},")
        comma = "," if index < len(masks) - 1 else ""
        lines.append("\t}" + comma)

    lines.append("};")
    lines.append("")

    OUTPUT.write_text("\n".join(lines))
    total = len(masks) * height * row_bytes
    print(f"wrote {OUTPUT}: {len(masks)} glyphs, {width}x{height}, "
          f"{row_bytes} B/row, {total} B of bitmap data")


if __name__ == "__main__":
    main()
